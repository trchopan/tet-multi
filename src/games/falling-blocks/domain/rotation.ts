export const getKickTests = (
	kind: PieceKind,
	from: PieceRotation,
	to: PieceRotation,
): readonly Kick[] => {
	if (kind === 'O') return [[0, 0]];
	return (kind === 'I' ? I_KICKS : JLSTZ_KICKS)[`${from}>${to}`] ?? [[0, 0]];
};
